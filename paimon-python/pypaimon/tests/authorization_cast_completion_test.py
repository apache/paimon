def source_array(values, type_):
    if pa.types.is_floating(type_):
        values = [None if v is None else float(v) for v in values]
    elif pa.types.is_binary(type_):
        values = [None if v is None else bytes(v) for v in values]
    elif pa.types.is_decimal(type_):
        values = [None if v is None else Decimal(v) for v in values]
    elif pa.types.is_timestamp(type_):
        quantum = {'s': 1000000000, 'ms': 1000000, 'us': 1000, 'ns': 1}[type_.unit]
        converted = []
        for v in values:
            if v is None:
                converted.append(None)
                continue
            millis = v['millis'] if isinstance(v, dict) else v
            nanos = v.get('nanos', 0) if isinstance(v, dict) else 0
            full = millis * 1000000 + nanos
            if full % quantum or not -(1 << 63) <= full // quantum < (1 << 63):
                raise OverflowError('Java timestamp cannot be stored in the Arrow source')
            converted.append(full // quantum)
        values = converted
    return pa.array(values, type=type_)


def external(array):
    type_ = array.type
    if pa.types.is_timestamp(type_):
        value = array.cast(pa.int64()).to_pylist()[0]
        if value is None:
            return None
        full = value * {'s': 1000000000, 'ms': 1000000, 'us': 1000, 'ns': 1}[type_.unit]
        return {'millis': full // 1000000, 'nanos': full % 1000000}
    if pa.types.is_date(type_) or pa.types.is_time(type_):
        return array.cast(pa.int32()).to_pylist()[0]
    value = array.to_pylist()[0]
    if isinstance(value, Decimal):
        return format(value, 'f')
    if isinstance(value, float) and math.isinf(value):
        return 'Infinity' if value > 0 else '-Infinity'
    return list(value) if isinstance(value, bytes) else value


def unrepresentable(expected, target):
    if not pa.types.is_timestamp(target) or not isinstance(expected, dict) or 'millis' not in expected:
        return False
    full = expected['millis'] * 1000000 + expected['nanos']
    quantum = {'s': 1000000000, 'ms': 1000000, 'us': 1000, 'ns': 1}[target.unit]
    return bool(full % quantum) or not -(1 << 63) <= full // quantum < (1 << 63)


def invalid_utf8(value, source):
    if value is None or not pa.types.is_binary(source):
        return False
    try:
        bytes(value).decode('utf8')
    except UnicodeDecodeError:
        return True
    return False


@pytest.mark.parametrize('zone', ['UTC', 'Asia/Shanghai', 'America/New_York'])
@pytest.mark.parametrize('case', JAVA_CASES, ids=lambda case: case['name'])
def test_scalar_cast_completion_matches_actual_java(case, zone, monkeypatch):
    monkeypatch.setenv('TZ', zone)
    time.tzset()
    try:
        source = _paimon_type_to_arrow(case['fields'][0]['type'])
        target = _paimon_type_to_arrow(case['transform']['type'])
        for row, expected in zip(case['rows'], case['expected'][zone]):
            try:
                array = source_array([row[0]], source)
            except OverflowError:
                continue
            batch = pa.RecordBatch.from_pydict({'v': array})
            error = (isinstance(expected, dict) and 'error' in expected
                     or unrepresentable(expected, target) or invalid_utf8(row[0], source))
            if error:
                with pytest.raises((ValueError, TypeError, OverflowError, pa.ArrowException)):
                    _apply_predicate_transform(case['transform'], batch)
            else:
                assert external(_apply_predicate_transform(case['transform'], batch)) == expected, row
    finally:
        monkeypatch.undo()
        time.tzset()


